def generate_csv_string():
    output = io.StringIO()
    fieldnames = [
        "product_id",
        "canonical_name",
        "brand",
        "category",
        "aliases_en",
        "aliases_gu",
        "aliases_hi",
        "common_ocr_errors",
        "units",
        "pack_sizes"
    ]
    writer = csv.DictWriter(output, fieldnames=fieldnames, lineterminator="\n")
    writer.writeheader()
    for prod in PRODUCTS:
        writer.writerow(prod)
    return output.getvalue()

def write_catalog(target_path: Path):
    content = generate_csv_string()
    target_path.write_text(content, encoding="utf-8")
    print(f"Catalog successfully written to: {target_path}")

if __name__ == "__main__":
    target = Path(__file__).resolve().parent.parent / "data" / "products.csv"
    write_catalog(target)
